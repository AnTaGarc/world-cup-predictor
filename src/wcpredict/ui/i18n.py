def normalise_language(value: object) -> Language | None:
    if not isinstance(value, str):
        return None
    normalized = value.strip().lower()
    return cast(Language, normalized) if normalized in SUPPORTED_LANGUAGES else None


def placeholders(message: Message) -> set[str]:
    templates = message.values() if isinstance(message, Mapping) else (message,)
    return {
        field
        for template in templates
        for _, field, _, _ in Formatter().parse(template)
        if field is not None
    }


def translate(
    key: str,
    *,
    language: Language,
    count: int | None = None,
    **values: object,
) -> str:
    try:
        message = CATALOGUES[language][key]
    except KeyError as exc:
        raise KeyError(f"Unknown translation key {key!r} for {language!r}") from exc
    if isinstance(message, Mapping):
        message = message["one" if count == 1 else "other"]
    parameters = dict(values)
    if count is not None:
        parameters["count"] = count
    try:
        return message.format(**parameters)
    except KeyError as exc:
        raise ValueError(f"Missing interpolation {exc.args[0]!r} for message {key!r}") from exc


def localize_controlled(kind: str, value: object, *, language: Language) -> object:
    if not isinstance(value, str):
        return value
    return CONTROLLED_VALUES.get(kind, {}).get(language, {}).get(value, value)


def localize_table_columns(rows: list[dict], *, language: Language) -> list[dict]:
    labels = TABLE_COLUMNS[language]
    return [
        {labels.get(str(key), str(key).replace("_", " ").capitalize()): value for key, value in row.items()}
        for row in rows
    ]
